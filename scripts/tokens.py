#!/usr/bin/env python3
"""Turns vomatt-web's color tokens (src/styles/global.css) into iOS colors.

Reads the OKLCh values under `:root` (light) and `.dark`, converts them to
Display P3 and writes one colorset per token into the asset catalog, plus a
Swift file naming each one. Tokens that alias another (`var(--x)`) are
skipped; tokens without a dark value reuse the light one.

Usage: tokens.py <global.css> <Colors.xcassets dir> <Tokens.generated.swift>
"""

import json
import math
import re
import shutil
import sys
from pathlib import Path

OKLCH = re.compile(r"--([\w-]+):\s*oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*\)\s*;")


def block(css: str, selector: str) -> str:
    match = re.search(re.escape(selector) + r"\s*\{(.*?)\n\}", css, re.S)
    if not match:
        sys.exit(f"tokens.py: no `{selector}` block in the stylesheet")
    return match.group(1)


def tokens(css_block: str) -> dict[str, tuple[float, float, float]]:
    return {name: (float(l), float(c), float(h)) for name, l, c, h in OKLCH.findall(css_block)}


def oklch_to_p3(l: float, c: float, h: float) -> tuple[float, float, float]:
    a = c * math.cos(math.radians(h))
    b = c * math.sin(math.radians(h))
    l_ = l + 0.3963377774 * a + 0.2158037573 * b
    m_ = l - 0.1055613458 * a - 0.0638541728 * b
    s_ = l - 0.0894841775 * a - 1.2914855480 * b
    lms = (l_**3, m_**3, s_**3)
    # OKLab LMS -> linear sRGB
    rgb = (
        4.0767416621 * lms[0] - 3.3077115913 * lms[1] + 0.2309699292 * lms[2],
        -1.2684380046 * lms[0] + 2.6097574011 * lms[1] - 0.3413193965 * lms[2],
        -0.0041960863 * lms[0] - 0.7034186147 * lms[1] + 1.7076147010 * lms[2],
    )
    # linear sRGB -> XYZ (D65) -> linear Display P3
    x = 0.4124564 * rgb[0] + 0.3575761 * rgb[1] + 0.1804375 * rgb[2]
    y = 0.2126729 * rgb[0] + 0.7151522 * rgb[1] + 0.0721750 * rgb[2]
    z = 0.0193339 * rgb[0] + 0.1191920 * rgb[1] + 0.9503041 * rgb[2]
    p3 = (
        2.4934969 * x - 0.9313836 * y - 0.4027108 * z,
        -0.8294890 * x + 1.7626641 * y + 0.0236247 * z,
        0.0358458 * x - 0.0761724 * y + 0.9568845 * z,
    )
    return tuple(gamma(min(1.0, max(0.0, channel))) for channel in p3)


def gamma(linear: float) -> float:
    return 12.92 * linear if linear <= 0.0031308 else 1.055 * linear ** (1 / 2.4) - 0.055


def color_entry(rgb, dark: bool):
    entry = {
        "color": {
            "color-space": "display-p3",
            "components": {
                "alpha": "1.000",
                "red": f"{rgb[0]:.4f}",
                "green": f"{rgb[1]:.4f}",
                "blue": f"{rgb[2]:.4f}",
            },
        },
        "idiom": "universal",
    }
    if dark:
        entry["appearances"] = [{"appearance": "luminosity", "value": "dark"}]
    return entry


def camel(name: str) -> str:
    head, *rest = name.split("-")
    return head + "".join(part.capitalize() for part in rest)


def main() -> None:
    css_path, catalog, swift_path = map(Path, sys.argv[1:4])
    css = css_path.read_text()
    light = tokens(block(css, ":root"))
    dark = tokens(block(css, ".dark"))

    if catalog.exists():
        shutil.rmtree(catalog)
    catalog.mkdir(parents=True)
    (catalog / "Contents.json").write_text(json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2))

    for name, value in sorted(light.items()):
        colorset = catalog / f"{name}.colorset"
        colorset.mkdir()
        colors = [color_entry(oklch_to_p3(*value), dark=False),
                  color_entry(oklch_to_p3(*dark.get(name, value)), dark=True)]
        (colorset / "Contents.json").write_text(
            json.dumps({"colors": colors, "info": {"author": "xcode", "version": 1}}, indent=2)
        )

    lines = [
        "// Generated by scripts/tokens.py from vomatt-web's src/styles/global.css. Do not edit.",
        "import SwiftUI",
        "",
        "/// The web's semantic color tokens; each has a light and a dark value.",
        "enum Tokens {",
    ]
    for name in sorted(light):
        lines.append(f'    static let {camel(name)} = Color("{name}")')
    lines += ["}", ""]
    swift_path.write_text("\n".join(lines))
    print(f"tokens.py: {len(light)} colors ({len(dark)} with dark values)")


if __name__ == "__main__":
    main()
